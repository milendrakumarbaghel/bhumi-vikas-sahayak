create table source_document (
    id bigint generated by default as identity primary key,
    title varchar(255) not null,
    language varchar(8) not null,
    authority varchar(255) not null,
    version_date date not null,
    resource_path varchar(1024) not null,
    sha256 varchar(64)
);

create table building_rule (
    id bigint generated by default as identity primary key,
    rule_number varchar(32) not null unique,
    title varchar(255) not null,
    part_name varchar(255) not null,
    page_start integer not null check (page_start > 0),
    page_end integer not null check (page_end >= page_start),
    full_text text not null
);

create table rule_passage (
    id bigint generated by default as identity primary key,
    rule_id bigint not null references building_rule(id) on delete cascade,
    label varchar(128) not null,
    page_start integer not null check (page_start > 0),
    page_end integer not null check (page_end >= page_start),
    text text not null
);

create index idx_rule_passage_rule on rule_passage(rule_id);
create index idx_rule_passage_lower_text on rule_passage using gin (to_tsvector('english', text));

create table rule_amendment (
    id bigint generated by default as identity primary key,
    rule_number varchar(64) not null,
    notification_number varchar(255) not null,
    effective_date date not null,
    replacement_text text not null,
    status varchar(16) not null check (status in ('DRAFT', 'REVIEWED', 'ACTIVE', 'RETIRED'))
);

create index idx_rule_amendment_effective
    on rule_amendment(rule_number, status, effective_date desc);
